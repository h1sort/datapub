"""Run the four SQL definitions in DuckDB and write deck/data/metric-a.js."""
import json
import os
from pathlib import Path

import duckdb

HERE = Path(__file__).parent
OUT = HERE.parent.parent / "deck" / "data" / "metric-a.js"

# label (Spanish, <= 8 words) and slide SQL (<= 8 lines, <= 60 chars/line).
# Simplified for display; faithful to definitions/*.sql.
SLIDE = {
    "a": ("Altas del último año; promedio por cliente", """\
SELECT avg(avg_gap) FROM per_customer
-- clientes: subscribed_at
--   BETWEEN '2025-10-01' AND '2026-09-30'
-- avg_gap: días promedio entre usos
--   consecutivos, por cliente"""),
    "b": ("Suscritos en el año; todos los usos juntos", """\
SELECT avg(gap) FROM gaps
-- clientes: suscritos en algún momento
--   de 2025-10-01 a 2026-09-30
--   (incluye los que empezaron antes)
-- gap: días entre usos consecutivos,
--   promediados sobre todos los usos"""),
    "c": ("Año 2025; días del periodo ÷ usos", """\
SELECT avg(days_observed / n_uses)
FROM clientes_2025
-- clientes: subscribed_at en 2025
-- days_observed: de la alta al 31-dic
--   (o la baja, si cancelaron antes)
-- n_uses: usos en 2025"""),
}
DEFINED = ("Definición con dueño: alta, sesión y corte", """\
-- DEFINITION.md v1 (dueño: Datos)
-- cliente = alta en 365 días al corte,
--   sin baja al 2026-09-30
-- uso = sesión (eventos < 30 min = 1)
-- >= 2 usos; gap = días entre sesiones
SELECT avg(gap) FROM sessions"""
)


def run(name: str) -> float:
    os.chdir(HERE)  # SQL files use relative paths: data/*.parquet
    con = duckdb.connect()
    return round(float(con.sql((HERE / "definitions" / f"{name}.sql").read_text()).fetchone()[0]), 1)


def check(sql: str):
    lines = sql.splitlines()
    assert len(lines) <= 8 and all(len(l) <= 60 for l in lines), sql


defs = []
for k in "abc":
    label, sql = SLIDE[k]
    check(sql)
    assert len(label.split()) <= 8, label
    defs.append({"id": k, "label": label, "sql": sql, "value": run(k), "unit": "días"})
check(DEFINED[1])
assert len(DEFINED[0].split()) <= 8
agreed = {"label": DEFINED[0], "sql": DEFINED[1], "value": run("agreed"), "unit": "días"}

doc = {
    "question": "frecuencia promedio en días de los clientes suscritos en el último año",
    "cutoff": "2026-09-30",
    "definitions": defs,
    "defined": agreed,
    "source": "demos/metric-a (synthetic data, DuckDB)",
}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// window.METRIC_A: generated by demos/metric-a/compute.py (see CONTRACT.md). Do not edit.\n"
    f"window.METRIC_A = {json.dumps(doc, ensure_ascii=False, indent=2)};\n"
)
for d in defs + [agreed]:
    print(d.get("id", "defined"), d["value"], d["unit"])
